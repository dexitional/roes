CREATE TABLE orders (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  reference VARCHAR(20) NOT NULL,
  user_id INT UNSIGNED NULL,
  customer_name VARCHAR(150) NOT NULL,
  email VARCHAR(190) NOT NULL,
  phone VARCHAR(20) NOT NULL,
  delivery_method ENUM('delivery','pickup') NOT NULL DEFAULT 'delivery',
  region VARCHAR(80) NULL,
  city VARCHAR(80) NULL,
  address VARCHAR(300) NULL,
  notes VARCHAR(500) NULL,
  subtotal DECIMAL(12,2) NOT NULL,
  delivery_fee DECIMAL(12,2) NOT NULL DEFAULT 0,
  discount DECIMAL(12,2) NOT NULL DEFAULT 0,
  total DECIMAL(12,2) NOT NULL,
  coupon_code VARCHAR(40) NULL,
  payment_method ENUM('momo','paystack') NOT NULL DEFAULT 'momo',
  payment_status ENUM('pending','submitted','paid','failed','refunded') NOT NULL DEFAULT 'pending',
  momo_sender VARCHAR(20) NULL,
  momo_transaction_id VARCHAR(60) NULL,
  status ENUM('pending','confirmed','processing','shipped','delivered','cancelled') NOT NULL DEFAULT 'pending',
  paid_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_orders_reference (reference),
  KEY ix_orders_user (user_id),
  KEY ix_orders_status (status, created_at),
  KEY ix_orders_created (created_at),
  CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
