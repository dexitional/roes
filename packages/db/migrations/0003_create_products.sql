CREATE TABLE products (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  legacy_id INT NULL,
  category_id INT UNSIGNED NULL,
  name VARCHAR(160) NOT NULL,
  slug VARCHAR(190) NOT NULL,
  sku VARCHAR(60) NULL,
  short_description VARCHAR(400) NULL,
  description MEDIUMTEXT NULL,
  price DECIMAL(12,2) NOT NULL DEFAULT 0,
  compare_at_price DECIMAL(12,2) NULL,
  cost_price DECIMAL(12,2) NULL,
  stock INT NOT NULL DEFAULT 0,
  track_stock TINYINT(1) NOT NULL DEFAULT 1,
  material VARCHAR(80) NULL,
  finish VARCHAR(80) NULL,
  gender ENUM('women','men','unisex') NOT NULL DEFAULT 'women',
  tags JSON NULL,
  is_featured TINYINT(1) NOT NULL DEFAULT 0,
  is_new TINYINT(1) NOT NULL DEFAULT 0,
  status ENUM('draft','active','archived') NOT NULL DEFAULT 'active',
  seo_title VARCHAR(120) NULL,
  seo_description VARCHAR(300) NULL,
  focus_keyword VARCHAR(120) NULL,
  view_count INT UNSIGNED NOT NULL DEFAULT 0,
  sold_count INT UNSIGNED NOT NULL DEFAULT 0,
  rating_avg DECIMAL(3,2) NOT NULL DEFAULT 0,
  rating_count INT UNSIGNED NOT NULL DEFAULT 0,
  published_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_products_slug (slug),
  UNIQUE KEY uq_products_legacy (legacy_id),
  UNIQUE KEY uq_products_sku (sku),
  KEY ix_products_category (category_id, status),
  KEY ix_products_status_created (status, created_at),
  KEY ix_products_price (price),
  FULLTEXT KEY ft_products_search (name, short_description, material),
  CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
